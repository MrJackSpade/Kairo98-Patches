CHARS = " ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz.,'!?-"


def glyph(c):
    """10 row bytes, the letter in the top 5 bits of the low 6 (bit 5 =
    leftmost pixel; bit 0, the sixth column, left empty)."""
    rows = _ART[c]
    assert len(rows) == 10 and all(len(r) == 5 for r in rows), c
    return bytes(sum(1 << (5 - i) for i, p in enumerate(r) if p == "#") for r in rows)


def table():
    """The glyphs of CHARS, 10 bytes each, in order."""
    return b"".join(glyph(c) for c in CHARS)
